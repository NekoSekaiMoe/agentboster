export type TranslationKey = keyof typeof enUS;

export type TranslationValues = Record<string, number | string>;

export function isLocale(value: string): value is Locale {
  return (locales as readonly string[]).includes(value);
}

export function normalizeLocale(value: string | null | undefined): Locale {
  if (!value) {
    return defaultLocale;
  }

  const normalized = value.toLowerCase().replaceAll('_', '-');

  if (normalized === 'en-gb' || normalized.startsWith('en-gb-')) {
    return 'en-GB';
  }

  if (
    normalized === 'en' ||
    normalized === 'en-us' ||
    normalized.startsWith('en-us-')
  ) {
    return 'en-US';
  }

  if (
    normalized === 'zh-hk' ||
    normalized.startsWith('zh-hk-') ||
    normalized.includes('-hk')
  ) {
    return 'zh-HK';
  }

  if (
    normalized === 'zh-tw' ||
    normalized.startsWith('zh-tw-') ||
    normalized === 'zh-hant' ||
    normalized.startsWith('zh-hant-') ||
    normalized.includes('-tw')
  ) {
    return 'zh-TW';
  }

  if (
    normalized === 'zh' ||
    normalized === 'zh-cn' ||
    normalized.startsWith('zh-cn-') ||
    normalized === 'zh-hans' ||
    normalized.startsWith('zh-hans-') ||
    normalized.includes('-cn')
  ) {
    return 'zh-CN';
  }

  if (normalized === 'ja' || normalized.startsWith('ja-')) {
    return 'ja';
  }

  if (normalized === 'ko' || normalized.startsWith('ko-')) {
    return 'ko';
  }

  return defaultLocale;
}

export function translate(
  locale: Locale,
  key: TranslationKey,
  values?: TranslationValues,
): string {
  const template =
    translations[locale][key] ?? translations[defaultLocale][key] ?? key;

  if (!values) {
    return template;
  }

  return template.replace(/\{(\w+)\}/g, (match, token: string) => {
    const value = values[token];
    return value === undefined ? match : String(value);
  });
}
